export function getStateCodeByName(stateName: string): string {
  const found = Object.values(STATE_CODE_MAP).find(
    (s) => s.name.toLowerCase().includes(stateName.toLowerCase()) || stateName.toLowerCase().includes(s.name.toLowerCase())
  );
  return found ? found.code : "ALL";
}

export function getStateNameByCode(code: string): string {
  const upper = code.toUpperCase();
  return STATE_CODE_MAP[upper]?.name || "All India / National";
}

